-- Разовая выдача 10 000 монет ВСЕМ УЖЕ СУЩЕСТВУЮЩИМ игрокам.
-- Новым игрокам 10 000 монет теперь выдаёт сам fn_ensure_profile
-- (приветственный бонус увеличен с 1000 до 10000 — см. supabase_schema.sql,
-- выполните его заново, если ещё не переустанавливали после этого патча).
--
-- Выполнить один раз в SQL Editor. Безопасно запускать повторно не нужно —
-- при повторном запуске каждый игрок получит ещё 10000, а не пропустится.
-- Если нужно защититься от случайного повторного запуска, добавьте перед
-- этим блоком проверку на существование записи с reason='bulk_grant_10000'
-- в coin_transactions.

do $$
declare r record;
begin
  for r in select yandex_id from profiles loop
    perform fn_add_coins(r.yandex_id, 10000, 'bulk_grant_10000', '{}'::jsonb);
  end loop;
end $$;
